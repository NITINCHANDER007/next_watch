// Generates procedural authentic-style episodes for any series that isn't hardcoded
export function generateProceduralSeasons(movie) {
  const durationMatch = movie?.duration?.match(/(\d+)\s*Season/i);
  const totalSeasons = Math.max(1, movie?.seasons || (durationMatch ? parseInt(durationMatch[1], 10) : (movie?.isSeries ? 3 : 1)));

  const seasons = [];
  const baseYear = movie?.releaseYear || 2022;

  for (let s = 1; s <= totalSeasons; s++) {
    const epCount = s === 1 ? 8 : (s % 2 === 0 ? 10 : 8);
    const episodes = [];

    for (let e = 1; e <= epCount; e++) {
      episodes.push({
        episodeNumber: e,
        seasonNumber: s,
        title: `Episode ${e}: ${getProceduralTitle(movie?.title || 'Story', s, e)}`,
        duration: `${42 + ((s * 3 + e * 7) % 18)}m`,
        synopsis: `Season ${s}, Episode ${e} of ${movie?.title}. In this chapter, unexpected tensions unfold as consequences from earlier choices escalate across the storyline.`,
        progress: (s === 1 && e === 1 ? 65 : s === 1 && e === 2 ? 30 : 0)
      });
    }

    seasons.push({
      seasonNumber: s,
      year: baseYear + (s - 1),
      episodes
    });
  }

  return { totalSeasons, seasons };
}

function getProceduralTitle(seriesTitle, season, ep) {
  const themes = [
    'The Genesis', 'Shadows of the Past', 'A Fragile Truce', 'Crossroads',
    'Whispers in the Dark', 'Point of No Return', 'The Reckoning', 'Ascension',
    'Retribution', 'Into the Fire', 'The Turning Tide', 'Dawn of Chaos'
  ];
  const idx = ((season - 1) * 3 + (ep - 1)) % themes.length;
  return themes[idx];
}

// Master resolver for any series: returns complete seasons list and episode list
export function getSeriesMetadata(movie) {
  if (!movie) return { totalSeasons: 1, seasons: [] };

  const id = String(movie.id || '').toLowerCase();
  const title = String(movie.title || '').toLowerCase().trim();

  // 1. Direct key match in detailed database
  if (DETAILED_SERIES_SEASONS[id]) {
    return DETAILED_SERIES_SEASONS[id];
  }

  // 2. Title key match
  for (const [key, data] of Object.entries(DETAILED_SERIES_SEASONS)) {
    if (title.includes(key.replace(/-/g, ' ')) || key.replace(/-/g, ' ').includes(title)) {
      return data;
    }
  }

  // 3. Procedural generator for any other series in catalog or dynamic search
  return generateProceduralSeasons(movie);
}

export function getSeasonEpisodes(movie, seasonNumber = 1) {
  const meta = getSeriesMetadata(movie);
  const foundSeason = meta.seasons.find((s) => s.seasonNumber === seasonNumber) || meta.seasons[0];
  return foundSeason ? foundSeason.episodes : [];
}
